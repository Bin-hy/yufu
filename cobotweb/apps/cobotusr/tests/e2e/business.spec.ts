test('撤销授权异步失败保持打开，防重复提交并恢复焦点', async ({ page, mock }) => {
    mock.failures.set('DELETE /oidc/authorized-apps/40', 1)
    mock.delays.set('DELETE /oidc/authorized-apps/40', 600)
    await page.goto('/authorized-apps')
    await page.getByRole('button', { name: '撤销', exact: true }).click()
    const dialog = page.getByRole('alertdialog')
    await expect(dialog).toBeVisible()
    await expect(dialog.getByRole('button', { name: '取消', exact: true })).toBeFocused()
    await dialog.getByRole('button', { name: '撤销授权', exact: true }).click()
    await expect(dialog.getByRole('button', { name: '处理中…', exact: true })).toBeDisabled()
    await page.keyboard.press('Escape')
    await expect(dialog).toBeVisible()
    await expect(dialog.getByRole('alert')).toContainText(mock.message)
    expect(mock.calls.filter((call) => call.method === 'DELETE')).toHaveLength(1)
    await dialog.getByRole('button', { name: '撤销授权', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await expect(page.getByRole('heading', { name: '尚未授权任何应用' })).toBeVisible()
})
